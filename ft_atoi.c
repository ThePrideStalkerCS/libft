#include "libft.h"

int	ft_atoi(const char *c)
{
	int	neg;
	int	ret;

	ret = 0;
	neg = 1;
	while ((*c >= 9 && *c <= 13) || *c == 32)
		c++;
	if (*c == '+' || *c == '-')
	{
		if (*c == '-')
			neg *= -1;
		c++;
	}
	while (*c >= '0' && *c <= '9')
	{
		ret = ret * 10 + (*c - '0');
		c++;
	}
	return (ret * neg);
}
